// Helper functions
export const getPublishedArticles = (): KnowledgeArticle[] => {
  return KNOWLEDGE_ARTICLES.filter((a) => a.isPublished);
};

export const getArticleBySlug = (slug: string): KnowledgeArticle | undefined => {
  if (!slug) return undefined;
  const normalized = slug.trim().toLowerCase();
  return KNOWLEDGE_ARTICLES.find(
    (a) => a.slug.toLowerCase() === normalized || a.id.toLowerCase() === normalized
  );
};

export const getArticlesByCategory = (categoryId: string): KnowledgeArticle[] => {
  if (!categoryId || categoryId === 'all') return getPublishedArticles();
  return getPublishedArticles().filter((a) => a.category === categoryId);
};

export const getFeaturedArticle = (): KnowledgeArticle | undefined => {
  return KNOWLEDGE_ARTICLES.find((a) => a.featured && a.isPublished) || KNOWLEDGE_ARTICLES[0];
};

export const getRelatedArticlesForArticle = (article: KnowledgeArticle): KnowledgeArticle[] => {
  const bySlug = article.relatedArticles
    .map((s) => getArticleBySlug(s))
    .filter((a): a is KnowledgeArticle => a !== undefined);

  if (bySlug.length >= 3) return bySlug.slice(0, 3);

  // Fill up with same category articles
  const sameCategory = KNOWLEDGE_ARTICLES.filter(
    (a) => a.id !== article.id && a.isPublished && a.category === article.category && !bySlug.some((b) => b.id === a.id)
  );

  return [...bySlug, ...sameCategory].slice(0, 3);
};
